"""CLI command for patch verification.

This module provides the `crsbench patch-verify` CLI command for verifying
CRS-generated patches against benchmark POVs.

Requires explicit patch input (--patch or --patch-dir) and POV input
(--pov or --pov-dir). For validating benchmark ground-truth patches,
use `crsbench ci patch` instead.

Usage:
    crsbench patch-verify <benchmark_path> --patch-dir ./patches --pov-dir ./povs [options]
    crsbench patch-verify <benchmark_path> --patch ./fix.diff --pov ./pov.blob [options]

Examples:
    # Verify patches in a directory against POVs
    crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \
        --patch-dir ./patches --pov-dir ./povs

    # Verify a single patch with a single POV
    crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \
        --patch ./my-patch.diff --pov ./pov.blob

    # Verify with specific harness filter
    crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \
        --patch-dir ./patches --pov-dir ./povs --harness curl_fuzzer_ws

    # Output results to JSON file
    crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \
        --patch-dir ./patches --pov-dir ./povs --output results.json --format json
"""

import argparse
import json
import time
from pathlib import Path
from typing import Optional

import yaml

from crsbench.evaluation.verification.models import (
    PatchInfo,
    PatchVerificationResult,
    PatchVerificationStatus,
    UnitTestMode,
)
from crsbench.evaluation.verification.patch import PatchVerificationEngine
from crsbench.utils.logger import get_logger

logger = get_logger(__name__)


def add_patch_verify_subparser(subparsers: argparse._SubParsersAction) -> None:
    """Add the patch-verify subcommand to argparse.

    Args:
        subparsers: Subparsers action from main argument parser
    """
    parser = subparsers.add_parser(
        "patch-verify",
        help="Verify CRS-generated patches",
        description=(
            "Verify patches generated by a CRS (Cyber Reasoning System) against "
            "benchmark POVs. Builds patched code using inc-build images, runs POV "
            "tests to ensure the patch fixes the vulnerability, and optionally "
            "runs unit tests to ensure no regressions.\n\n"
            "Two modes are supported:\n"
            "  1. Single patch: Verify a single patch file with --patch\n"
            "  2. Directory: Verify all patches in a directory with --patch-dir\n\n"
            "For validating benchmark ground-truth patches, use 'crsbench ci patch' instead."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Verify all patches in a directory
  crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \\
      --patch-dir ./patches --pov-dir ./povs

  # Verify a single patch file with single POV
  crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \\
      --patch ./my-patch.diff --pov ./pov.blob

  # Filter to specific harness
  crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \\
      --patch-dir ./patches --pov-dir ./povs --harness curl_fuzzer_ws

  # Use RTS mode for faster tests
  crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \\
      --patch-dir ./patches --pov-dir ./povs --test-mode rts

  # Output results as JSON
  crsbench patch-verify benchmarks/aixcc/c/afc-curl-delta-01 \\
      --patch-dir ./patches --pov-dir ./povs --output results.json --format json
        """,
    )

    # Required arguments
    parser.add_argument(
        "benchmark_path",
        type=Path,
        help="Path to the benchmark project directory",
    )

    # Patch input (one required)
    patch_group = parser.add_mutually_exclusive_group(required=True)
    patch_group.add_argument(
        "--patch",
        type=Path,
        help="Single patch file to verify",
    )
    patch_group.add_argument(
        "--patch-dir",
        type=Path,
        help="Directory containing patches (structure: <pov_id>/patch.diff)",
    )

    # POV input (one required)
    pov_group = parser.add_mutually_exclusive_group(required=True)
    pov_group.add_argument(
        "--pov",
        type=Path,
        help="Single POV file to verify against",
    )
    pov_group.add_argument(
        "--pov-dir",
        type=Path,
        help="Directory containing POV files to verify against",
    )

    # Harness (optional - tests all harnesses if not specified)
    parser.add_argument(
        "--harness",
        type=str,
        default=None,
        help="Harness name to test against (default: all harnesses)",
    )

    # OSS-Fuzz path
    parser.add_argument(
        "--oss-fuzz",
        type=Path,
        default=None,
        help="Path to oss-fuzz directory (default: ./oss-fuzz)",
    )

    # Source mode
    parser.add_argument(
        "--source",
        type=str,
        default="main_repo",
        choices=["pkgs", "main_repo"],
        help="Source for benchmark code: 'main_repo' clones from repository (default), "
        "'pkgs' uses bundled tarballs",
    )

    # Test mode
    parser.add_argument(
        "--test-mode",
        type=str,
        choices=["full", "rts"],
        default="full",
        help="Unit test execution mode (default: full)",
    )

    # Sanitizer
    parser.add_argument(
        "--sanitizer",
        type=str,
        default="address",
        choices=["address", "undefined", "memory"],
        help="Sanitizer type (default: address)",
    )

    # Timeouts
    parser.add_argument(
        "--timeout",
        type=int,
        default=120,
        help="Timeout for POV reproduce operations in seconds (default: 120)",
    )

    parser.add_argument(
        "--build-timeout",
        type=int,
        default=1200,
        help="Timeout for build operations in seconds (default: 1200)",
    )

    parser.add_argument(
        "--test-timeout",
        type=int,
        default=1800,
        help="Timeout for unit test execution in seconds (default: 1800)",
    )

    # Parallel execution
    parser.add_argument(
        "--build-workers",
        type=int,
        default=None,
        help="Number of parallel workers for patch builds (default: 4). "
        "Priority: CLI > CRSBENCH_BUILD_WORKERS env.",
    )

    parser.add_argument(
        "--verify-workers",
        type=int,
        default=None,
        help="Number of parallel workers for patch verification (default: 4). "
        "Priority: CLI > CRSBENCH_VERIFY_WORKERS env.",
    )

    parser.add_argument(
        "--no-variants",
        action="store_true",
        help="Disable POV variant verification (only test original POV)",
    )

    # Force rebuild option
    parser.add_argument(
        "--force-rebuild",
        action="store_true",
        help="Force rebuild even if build cache exists",
    )

    parser.add_argument(
        "--no-inc-build",
        action="store_true",
        help="Disable incremental builds, use full OSS-Fuzz build instead",
    )

    # Output options
    parser.add_argument(
        "--output",
        "-o",
        type=Path,
        default=None,
        help="Output file path for results",
    )

    parser.add_argument(
        "--format",
        type=str,
        default="text",
        choices=["json", "yaml", "text"],
        help="Output format (default: text)",
    )

    parser.add_argument(
        "--verbose",
        "-v",
        action="store_true",
        help="Enable verbose output",
    )

    parser.set_defaults(func=run_patch_verify)


def run_patch_verify(args: argparse.Namespace) -> int:
    """Execute the patch-verify command.

    Two modes are supported:
    1. Single patch mode (--patch): Verify a single patch file
    2. Directory mode (--patch-dir): Verify all patches in a directory

    When --harness is not specified, tests against all harnesses from the benchmark.

    Args:
        args: Parsed command-line arguments

    Returns:
        Exit code (0 for success, non-zero for errors)
    """
    from crsbench.utils.logger import configure_logger

    log_level = "DEBUG" if args.verbose else "INFO"
    configure_logger(level=log_level)

    # Validate benchmark path
    if not args.benchmark_path.exists():
        logger.error(f"Benchmark path not found: {args.benchmark_path}")
        return 1

    # Validate inputs
    if args.patch is not None and not args.patch.exists():
        logger.error(f"Patch file not found: {args.patch}")
        return 1
    if args.patch_dir is not None and not args.patch_dir.exists():
        logger.error(f"Patch directory not found: {args.patch_dir}")
        return 1
    if args.pov is not None and not args.pov.exists():
        logger.error(f"POV file not found: {args.pov}")
        return 1
    if args.pov_dir is not None and not args.pov_dir.exists():
        logger.error(f"POV directory not found: {args.pov_dir}")
        return 1

    # Determine oss-fuzz path
    oss_fuzz_path = args.oss_fuzz or Path("./oss-fuzz")
    if not oss_fuzz_path.exists():
        logger.error(f"OSS-Fuzz directory not found: {oss_fuzz_path}")
        return 1

    # Create patch verification engine
    engine = PatchVerificationEngine(
        oss_fuzz_path=oss_fuzz_path,
        test_mode=UnitTestMode(args.test_mode),
        sanitizer=args.sanitizer,
        timeout=args.timeout,
        build_timeout=args.build_timeout,
        test_timeout=args.test_timeout,
        build_workers=args.build_workers,
        verify_workers=args.verify_workers,
        verify_variants=not args.no_variants,
        force_rebuild=args.force_rebuild,
        use_inc_build=not args.no_inc_build,
        source_mode=args.source,
    )

    # Resolve harness names
    harness_names = _resolve_harness_names(engine, args.benchmark_path, args.harness)
    if not harness_names:
        logger.error("No harnesses found for benchmark")
        return 1

    mode = "single" if args.patch is not None else "directory"
    logger.info(f"Verifying patches for benchmark: {args.benchmark_path}")
    logger.info(f"Mode: {mode}, Harnesses: {harness_names}")
    if args.force_rebuild:
        logger.info("Force rebuild enabled")

    try:
        results: list[PatchVerificationResult] = []
        wall_clock_start = time.time()

        if mode == "single":
            logger.info(f"Verifying single patch: {args.patch}")

            patch_info = PatchInfo(
                patch_id=args.patch.stem,
                pov_id="pov_0",
                patch_path=args.patch,
            )

            # Get POV path
            if args.pov is not None:
                pov_path = args.pov
            else:
                pov_path = _find_first_pov(args.pov_dir)
                if pov_path is None:
                    logger.error(f"No POV files found in {args.pov_dir}")
                    return 1

            for harness in harness_names:
                result = engine.verify_patch(
                    benchmark_path=args.benchmark_path,
                    patch=patch_info,
                    harness=harness,
                    pov_path=pov_path,
                )
                results.append(result)

        else:  # directory mode
            pov_dir = args.pov_dir if args.pov_dir else args.pov.parent
            logger.info(f"Patch directory: {args.patch_dir}")
            logger.info(f"POV directory: {pov_dir}")

            for harness in harness_names:
                harness_results = engine.verify_patches(
                    benchmark_path=args.benchmark_path,
                    patch_dir=args.patch_dir,
                    harness=harness,
                    pov_dir=pov_dir,
                )
                results.extend(harness_results)

        wall_clock_time = time.time() - wall_clock_start

        if not results:
            logger.warning("No verification results generated")
            return 0

        # Output results
        output_results(
            results, args.output, args.format, wall_clock_time=wall_clock_time
        )

        # Print summary
        print_summary(results, wall_clock_time=wall_clock_time)

        # Return non-zero if any patch failed
        valid_count = sum(
            1 for r in results if r.status == PatchVerificationStatus.VALID
        )
        return 0 if valid_count == len(results) else 1

    finally:
        engine.cleanup()


def _resolve_harness_names(
    engine: PatchVerificationEngine,
    benchmark_path: Path,
    harness: Optional[str],
) -> list[str]:
    """Resolve harness names to test against.

    When harness is specified, returns [harness]. Otherwise loads the
    adapter and returns all harness names from meta.yaml.

    Args:
        engine: PatchVerificationEngine instance
        benchmark_path: Path to benchmark directory
        harness: Optional harness name filter

    Returns:
        List of harness names to test
    """
    if harness:
        return [harness]

    adapter = engine._load_adapter(benchmark_path)
    if not adapter:
        logger.error(f"Failed to load benchmark adapter for {benchmark_path}")
        return []

    return adapter.get_harness_names()


def _find_first_pov(pov_dir: Path) -> Optional[Path]:
    """Find the first POV file in a directory.

    Args:
        pov_dir: Directory to search

    Returns:
        Path to first POV file, or None if not found
    """
    for ext in ["*.blob", "*.bin", "*.pov", "*"]:
        files = list(pov_dir.glob(ext))
        for f in files:
            if f.is_file():
                return f
    return None


def output_results(
    results: list[PatchVerificationResult],
    output_path: Optional[Path],
    output_format: str,
    *,
    wall_clock_time: float = 0.0,
) -> None:
    """Output verification results.

    Args:
        results: List of patch verification results
        output_path: Optional output file path
        output_format: Output format (json, yaml, text)
        wall_clock_time: Total wall-clock time for the entire run
    """
    result_dicts = [r.to_dict() for r in results]

    if output_format == "json":
        output_data = {
            "results": result_dicts,
            "wall_clock_time": wall_clock_time,
        }
        output = json.dumps(output_data, indent=2)
    elif output_format == "yaml":
        output_data = {
            "results": result_dicts,
            "wall_clock_time": wall_clock_time,
        }
        output = yaml.dump(output_data, default_flow_style=False)
    else:  # text
        lines = []
        for r in results:
            status_icon = "+" if r.status == PatchVerificationStatus.VALID else "x"
            verdict_str = f" [{r.security_verdict}]"
            lines.append(f"{status_icon} {r.pov_id}: {r.status.value}{verdict_str}")

            if r.harness:
                lines.append(f"    Harness: {r.harness}")

            if r.cpv_fixed:
                lines.append(f"    CPVs fixed: {', '.join(r.cpv_fixed)}")

            if r.scores is not None:
                lines.append(
                    f"    Fix rate: {r.scores.overall_fix_rate:.1%} "
                    f"({r.scores.total_variants_matched}/{r.scores.total_variants_tested} variants)"
                )
                lines.append(
                    f"    CPV breakdown: {r.scores.cpvs_complete} complete, "
                    f"{r.scores.cpvs_partial} partial, {r.scores.cpvs_none} none"
                )

            if r.details:
                lines.append(f"    Details: {r.details}")
            # Print timing: build, pov, unit, total
            if r.build_time > 0 or r.elapsed_seconds > 0:
                timing_parts = []
                if r.build_time > 0:
                    timing_parts.append(f"build: {r.build_time:.2f}s")
                if r.pov_test_time > 0:
                    timing_parts.append(f"pov: {r.pov_test_time:.2f}s")
                if r.unit_test_time > 0:
                    timing_parts.append(f"unit: {r.unit_test_time:.2f}s")
                if r.elapsed_seconds > 0:
                    timing_parts.append(f"total: {r.elapsed_seconds:.2f}s")
                lines.append(f"    Time: {', '.join(timing_parts)}")
        output = "\n".join(lines)

    if output_path:
        output_path.write_text(output)
        logger.info(f"Results written to: {output_path}")
    else:
        logger.info(output)


def print_summary(
    results: list[PatchVerificationResult],
    *,
    wall_clock_time: float = 0.0,
) -> None:
    """Print a summary of patch verification results.

    Args:
        results: List of patch verification results
        wall_clock_time: Total wall-clock time for the entire run
    """
    from collections import Counter

    status_counts = Counter(r.status.value for r in results)

    valid_count = sum(1 for r in results if r.status == PatchVerificationStatus.VALID)
    total_count = len(results)

    # Count security verdicts
    pass_count = sum(1 for r in results if r.security_verdict == "PASS")
    fail_count = sum(1 for r in results if r.security_verdict == "FAIL")

    # Aggregate CPVs fixed across all patches
    all_cpvs_fixed: set[str] = set()
    total_cpvs_complete = 0
    total_cpvs_partial = 0
    total_cpvs_none = 0
    total_variants_tested = 0
    total_variants_matched = 0

    for r in results:
        all_cpvs_fixed.update(r.cpv_fixed)
        if r.scores is not None:
            total_cpvs_complete += r.scores.cpvs_complete
            total_cpvs_partial += r.scores.cpvs_partial
            total_cpvs_none += r.scores.cpvs_none
            total_variants_tested += r.scores.total_variants_tested
            total_variants_matched += r.scores.total_variants_matched

    logger.info("\n" + "=" * 60)
    logger.info("PATCH VERIFICATION SUMMARY")
    logger.info("=" * 60)
    logger.info(f"Total patches verified: {total_count}")
    logger.info(f"Valid patches: {valid_count}/{total_count}")
    logger.info("")
    logger.info("Security Verdicts:")
    logger.info(f"  PASS: {pass_count}")
    logger.info(f"  FAIL: {fail_count}")
    logger.info("")
    logger.info("Status breakdown:")
    for status, count in sorted(status_counts.items()):
        logger.info(f"  {status}: {count}")

    if all_cpvs_fixed or total_variants_tested > 0:
        logger.info("")
        logger.info("Aggregate CPV Statistics:")
        logger.info(f"  Unique CPVs fixed: {len(all_cpvs_fixed)}")
        if all_cpvs_fixed:
            logger.info(f"    CPVs: {', '.join(sorted(all_cpvs_fixed))}")
        logger.info(
            f"  CPV outcomes: {total_cpvs_complete} complete, "
            f"{total_cpvs_partial} partial, {total_cpvs_none} none"
        )
        if total_variants_tested > 0:
            overall_rate = total_variants_matched / total_variants_tested
            logger.info(
                f"  Overall fix rate: {overall_rate:.1%} "
                f"({total_variants_matched}/{total_variants_tested} variants)"
            )

    # Timing summary
    if wall_clock_time > 0:
        logger.info("")
        logger.info("Timing:")
        logger.info(f"  Wall-clock time: {wall_clock_time:.2f}s")

    logger.info("=" * 60)


def main() -> None:
    """Main entry point for standalone execution."""
    import sys

    parser = argparse.ArgumentParser(
        description="CRSBench Patch Verification Tool",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    subparsers = parser.add_subparsers(dest="command", help="Available commands")
    add_patch_verify_subparser(subparsers)

    args = parser.parse_args()

    if args.command is None:
        parser.print_help()
        sys.exit(0)

    if hasattr(args, "func"):
        sys.exit(args.func(args))
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == "__main__":
    main()
